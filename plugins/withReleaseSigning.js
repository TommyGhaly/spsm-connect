/**
 * Sign the Android release with the church's upload key instead of the debug one.
 *
 * ---------------------------------------------------------------------------
 * ## The failure this exists to prevent
 *
 * The React Native template ships this, and it survived into every build this
 * project has made:
 *
 *     release {
 *         // Caution! In production, you need to generate your own keystore file.
 *         signingConfig signingConfigs.debug
 *     }
 *
 * A release AAB signed with `debug.keystore` — whose password is the literal
 * string `android`, committed to this repository and identical on every React
 * Native project on earth. Play refuses it. If it did not refuse it, the
 * outcome would be worse: the first upload of an app permanently binds the
 * package name to whatever key signed it, and binding `org.spsm.connect` to a
 * public key would mean anyone could publish an update to the church's app.
 *
 * ## Why a plugin and not an edit to android/app/build.gradle
 *
 * `/android` is gitignored — see .gitignore, "generated native folders". The
 * directory is rebuilt by `npx expo prebuild --clean`, so an edit made there by
 * hand is correct until the next prebuild and then silently gone, most likely
 * on the machine doing the release. Prebuild regenerates from config plugins;
 * this is the only place the change can live and stay.
 *
 * ## The keystore is never in this repository, and neither are its passwords
 *
 * Four Gradle properties, and the only sensible home for them is
 * `~/.gradle/gradle.properties` on the machine that signs — outside the repo,
 * outside any build context that gets uploaded, and already the file Gradle
 * reads for exactly this purpose:
 *
 *     SPSM_UPLOAD_STORE_FILE=/absolute/path/to/spsm-upload.jks
 *     SPSM_UPLOAD_KEY_ALIAS=spsm-upload
 *     SPSM_UPLOAD_STORE_PASSWORD=…
 *     SPSM_UPLOAD_KEY_PASSWORD=…
 *
 * An absolute path, because Gradle resolves a relative one against
 * `android/app/` — which is regenerated, so a keystore kept inside it is one
 * `prebuild --clean` away from being deleted along with the ability to publish
 * an update to this app ever again. Keep it outside the repository and backed
 * up; a lost upload key is recoverable only through Play support, and only if
 * Play App Signing was enrolled.
 *
 * Generated by whoever holds the church's developer account, not by this
 * script and not by anything that could put it in a log:
 *
 *     keytool -genkeypair -v -keystore spsm-upload.jks -alias spsm-upload \
 *       -keyalg RSA -keysize 2048 -validity 10000
 *
 * ## Absent properties fall back to debug signing, deliberately
 *
 * `npx expo run:android --variant release` is a thing people do to check that
 * a release build runs at all, and it must not require the church's signing
 * key to be on the laptop. So the release config only takes effect when all
 * four properties are present; otherwise the build signs as it did before and
 * is perfectly usable for everything except uploading.
 *
 * The trap in that arrangement is a silent fallback at the moment it matters —
 * a release build for Play, signed with the debug key because of a typo in a
 * property name, which looks completely normal until Play rejects it. So the
 * generated Gradle prints which key it used, every time, and
 * `SPSM_REQUIRE_UPLOAD_KEY=1` turns the fallback into a hard failure for the
 * build that is actually going to the store.
 * ---------------------------------------------------------------------------
 */
const { withAppBuildGradle } = require('@expo/config-plugins');

/** The four properties, named together so the Gradle and the prose agree. */
const STORE_FILE = 'SPSM_UPLOAD_STORE_FILE';
const KEY_ALIAS = 'SPSM_UPLOAD_KEY_ALIAS';
const STORE_PASSWORD = 'SPSM_UPLOAD_STORE_PASSWORD';
const KEY_PASSWORD = 'SPSM_UPLOAD_KEY_PASSWORD';

/**
 * The template's `signingConfigs` block, matched exactly.
 *
 * Anchored on the closing brace of `debug` plus the block's own, rather than on
 * `signingConfigs {` alone, so that appending is unambiguous. If the template
 * changes this shape the plugin throws rather than producing a build.gradle
 * that looks edited and is not.
 */
const SIGNING_CONFIGS = `    signingConfigs {
        debug {
            storeFile file('debug.keystore')
            storePassword 'android'
            keyAlias 'androiddebugkey'
            keyPassword 'android'
        }
    }`;

const WITH_RELEASE = `    signingConfigs {
        debug {
            storeFile file('debug.keystore')
            storePassword 'android'
            keyAlias 'androiddebugkey'
            keyPassword 'android'
        }
        // Written by plugins/withReleaseSigning.js. The four properties live in
        // ~/.gradle/gradle.properties on the machine that signs, never here.
        release {
            if (project.hasProperty('${STORE_FILE}')) {
                storeFile file(project.property('${STORE_FILE}'))
                keyAlias project.property('${KEY_ALIAS}')
                storePassword project.property('${STORE_PASSWORD}')
                keyPassword project.property('${KEY_PASSWORD}')
            }
        }
    }`;

/**
 * The template's release signing line, and what replaces it.
 *
 * `hasUploadKey` is computed once and used twice — for the choice and for the
 * message — so the two can never disagree about which key was used.
 */
const RELEASE_SIGNING = `        release {
            // Caution! In production, you need to generate your own keystore file.
            // see https://reactnative.dev/docs/signed-apk-android.
            signingConfig signingConfigs.debug`;

const RELEASE_SIGNING_FIXED = `        release {
            // Written by plugins/withReleaseSigning.js, replacing the template's
            // \`signingConfig signingConfigs.debug\`. See that file.
            def hasUploadKey = project.hasProperty('${STORE_FILE}') &&
                project.hasProperty('${KEY_ALIAS}') &&
                project.hasProperty('${STORE_PASSWORD}') &&
                project.hasProperty('${KEY_PASSWORD}')

            if (hasUploadKey) {
                println '[spsm] release signing: the church upload key (' + project.property('${KEY_ALIAS}') + ')'
                signingConfig signingConfigs.release
            } else if (project.hasProperty('SPSM_REQUIRE_UPLOAD_KEY')) {
                throw new GradleException(
                    'SPSM_REQUIRE_UPLOAD_KEY is set but the upload key properties are missing. ' +
                    'Expected ${STORE_FILE}, ${KEY_ALIAS}, ${STORE_PASSWORD} and ${KEY_PASSWORD} ' +
                    'in ~/.gradle/gradle.properties. See plugins/withReleaseSigning.js.')
            } else {
                println '[spsm] release signing: DEBUG KEY — runnable, NOT uploadable to Play. ' +
                    'See plugins/withReleaseSigning.js.'
                signingConfig signingConfigs.debug
            }`;

module.exports = function withReleaseSigning(config) {
  return withAppBuildGradle(config, (mod) => {
    if (mod.modResults.language !== 'groovy') {
      throw new Error(
        `withReleaseSigning expected a Groovy build.gradle, found ${mod.modResults.language}.`,
      );
    }

    let contents = mod.modResults.contents;

    /*
     * Idempotent, because prebuild may run this over an android/ directory that
     * already has it — and appending a second `release` signing config would
     * fail the Gradle build with a duplicate rather than doing nothing.
     */
    if (contents.includes('withReleaseSigning.js')) {
      return mod;
    }

    if (!contents.includes(SIGNING_CONFIGS)) {
      throw new Error(
        "withReleaseSigning could not find the template's `signingConfigs` block in " +
          'android/app/build.gradle. The template has changed; check what signs the release ' +
          'before trusting this plugin.',
      );
    }

    if (!contents.includes(RELEASE_SIGNING)) {
      throw new Error(
        "withReleaseSigning could not find the template's `signingConfig signingConfigs.debug` " +
          'in the release buildType. The template has changed; check what signs the release ' +
          'before trusting this plugin.',
      );
    }

    contents = contents.replace(SIGNING_CONFIGS, WITH_RELEASE);
    contents = contents.replace(RELEASE_SIGNING, RELEASE_SIGNING_FIXED);

    mod.modResults.contents = contents;
    return mod;
  });
};
